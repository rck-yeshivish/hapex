PUNCT = re.compile(r"[\'\"’”“‘״׳`\u05F3\u05F4\.\s]")
def norm_book(s): return ALIAS.get(PUNCT.sub("",s))
VAL = {}
for i,c in enumerate("אבגדהוזחט"): VAL[c]=i+1
for i,c in enumerate("יכלמנסעפצ"): VAL[c]=(i+1)*10
