def gem(s):
    s=PUNCT.sub("",s)
    if not s or any(c not in VAL for c in s): return None
    return sum(VAL[c] for c in s)
def parse_ref(ref):
    ref=ref.strip()
    m=re.match(r"^(.*?)\s+([^\s:]+)[:.]([^\s:]+)\s*$",ref)
    if not m: return None
    book=norm_book(m.group(1)); ch=gem(m.group(2)); v=gem(m.group(3))
    if not book or ch is None or v is None: return None
    return book,ch,v
